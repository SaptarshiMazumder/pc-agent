"""story_make — make an approved story: one campaign per product it shows, each with one stage per
shot (its count, shape and length), on the template that fits how the shots are made. The briefs
are written from the story; nothing paid runs until the user generates each stage."""

from __future__ import annotations

import asyncio

from agent_runtime.application.interfaces.tool import Tool, ToolResult
from agent_runtime.application.run_context import current_run_context
from agent_runtime.application.tool_models import brain_model, resolve_tool_model

from ad_generation.application.campaign_view_service import CampaignViewService
from ad_generation.application.story_campaigns import StoryCampaigns
from ad_generation.domain.creative_direction import CreativeDirection
from ad_generation.infrastructure.model_access_reasoner import ModelAccessReasoner
from ad_generation.infrastructure.vision_image_preparer import VisionImagePreparer
from ad_generation.presentation.generation_backend_resolver import PLUGIN, plugin_setting
from ad_generation.presentation.tool_progress_reporter import ToolProgressReporter


class StoryMakeTool(Tool):
    name = "story_make"
    label = "Make a story"
    plugin = PLUGIN
    needs_model = True
    model_kind = "vision"
    default_timeout_sec = 900.0
    description = (
        "Make an APPROVED story: one campaign per product it shows, one stage per shot. `template` is HOW "
        "the shots are made — the recipe that fits them (ethnic-wear, jewellery-model, wearable, handheld, "
        "product-stills, animate-image…). `cast`: who is in it (a cast name, or 'none'), only as the user "
        "chose. It reads each product and writes each brief; generating stays the user's, stage by stage."
    )
    parameters = {
        "type": "object",
        "required": ["story", "template"],
        "properties": {
            "story": {"type": "string"},
            "template": {"type": "string", "description": "The recipe key that fits how its shots are made."},
            "cast": {"type": "string", "description": "Who is in it, as the user chose: a cast name, or 'none'."},
            "templates": {"type": "object", "description": "Per product key, its own template when its shots are made differently (e.g. jewellery → jewellery-model)."},
        },
    }

    def __init__(self, config, service_factory, campaigns: StoryCampaigns, views: CampaignViewService, images: VisionImagePreparer) -> None:
        self.config = config
        self._service_factory = service_factory
        self._campaigns = campaigns
        self._views = views
        self._images = images

    async def execute(self, tool_call_id, params, abort, on_update=None):
        try:
            def reasoner(tool: str, kind: str) -> ModelAccessReasoner:
                model = resolve_tool_model(self.config, PLUGIN, tool, kind=kind) or brain_model(self.config)
                return ModelAccessReasoner(self.models, model, self._images, timeout_s=150)

            service = self._service_factory(
                reasoner("product_analyze", "vision"), reasoner("campaign_brief", "text"), reasoner("media_check", "vision"),
                ToolProgressReporter(asyncio.get_running_loop(), on_update),
            )
            cast = str(params.get("cast") or "")
            session = str(getattr(current_run_context(), "session_key", "") or "")
            approval = str(plugin_setting(self.config, "generation_approval", "ask"))

            def start(name: str, photos: list[str], plan: dict) -> str:
                campaign_id, _ = service.start(
                    name, photos, "", CreativeDirection(), "", session, approval, None,
                    {"cast": cast} if cast else {}, story_plan=plan,
                )
                return campaign_id

            ids = await asyncio.to_thread(
                self._campaigns.make, str(params.get("story") or ""), str(params.get("template") or ""), start,
                {str(k): str(v) for k, v in (params.get("templates") or {}).items()},
            )
            details = [self._views.detail(i) for i in ids]
        except Exception as e:  # noqa: BLE001 — every failure is reported, with its reason
            return ToolResult.text(f"story_make: {type(e).__name__}: {e}", is_error=True)
        lines = []
        for d in details:
            waiting = [s["label"] for st in d["steps"] if st["action"] == "brief" and st["status"] == "todo" for s in st["settings"] if s["missing"]]
            stages = ", ".join(f"{st['title']}" for st in d["steps"] if st["action"] in ("images", "video"))
            lines.append(f"{d['campaign_id']} ({d['product']['name']}): " + (f"waiting for: {', '.join(waiting)}" if waiting else "brief written") + f" · stages: {stages}")
        return ToolResult.text("\n".join(lines) + "\nNEXT: say which campaigns were made; each stage is generated by the user in the studio.", details={"campaigns": details})
